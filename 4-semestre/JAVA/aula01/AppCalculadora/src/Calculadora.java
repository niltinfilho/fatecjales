public class Calculadora {
    double number1;
    double number2;

    double somar() {
        return this.number1 + this.number2;
    }

    double subtrair() {
        return this.number1 - this.number2;
    }

    double multiplicar() {
        return this.number1 * this.number2;
    }

    double dividir() {
        return this.number1 / this.number2;
    }

}
